#!/usr/bin/env python3
"""Run T3-Video renders on Kaggle's free T4 x2 from here; nothing runs on your laptop.

    python submit.py check                       # credentials work, weekly GPU quota left
    python submit.py push [--only a,b] [--steps 15] [--shots shots.json]
    python submit.py status
    python submit.py logs [--follow]
    python submit.py wait [--every 900]          # poll until the run ends, then fetch
    python submit.py fetch                       # pull the latest run's outputs into renders/

push packs render.py + lowmem.py + the shot list into one Kaggle script, skips
shots that already have renders/<id>.mp4, and starts it on GPU T4 x2 with
internet on. The Kaggle job keeps running if this machine goes away; its
outputs stay on Kaggle until the next push, and push fetches them first.

Needs `pip install kaggle` and, in the environment, KAGGLE_USERNAME plus
KAGGLE_API_TOKEN (new tokens) or KAGGLE_KEY (legacy kaggle.json key).
"""
import argparse
import base64
import json
import os
import shutil
import subprocess
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
BUILD = os.path.join(HERE, "build")
KERNEL_DIR = os.path.join(BUILD, "kernel")
STATE = os.path.join(BUILD, "last_run.json")
RENDERS = os.path.join(HERE, "renders")
SLUG = "t3-video-render"
ACCELERATOR = "NvidiaTeslaT4"  # GPU T4 x2; Kaggle retired the P100

BOOTSTRAP = '''# Generated by t3-video/submit.py. Edit render.py, lowmem.py or shots.json instead.
import base64, os, subprocess, sys
FILES = {files}
ARGS = {args}
job = "/tmp/t3job"
os.makedirs(job, exist_ok=True)
for name, data in FILES.items():
    with open(os.path.join(job, name), "wb") as f:
        f.write(base64.b64decode(data))
os.makedirs("/kaggle/working", exist_ok=True)
cmd = [sys.executable, "-u", os.path.join(job, "render.py"), "run", "--shots", os.path.join(job, "shots.json")] + ARGS
with open("/kaggle/working/run.log", "w") as logf:
    p = subprocess.Popen(cmd, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True, bufsize=1)
    for line in p.stdout:
        sys.stdout.write(line)
        logf.write(line)
        logf.flush()
sys.exit(p.wait())
'''


def kaggle_cmd():
    exe = shutil.which("kaggle")
    return [exe] if exe else [sys.executable, "-c", "from kaggle.cli import main; main()"]


def kaggle(*args, capture=False, check=True):
    cmd = kaggle_cmd() + list(args)
    if capture:
        r = subprocess.run(cmd, capture_output=True, text=True)
        if check and r.returncode:
            sys.exit(f"kaggle {' '.join(args)} failed:\n{r.stdout}{r.stderr}")
        return r.stdout + r.stderr
    r = subprocess.run(cmd)
    if check and r.returncode:
        sys.exit(f"kaggle {' '.join(args)} failed (exit {r.returncode})")
    return ""


def user():
    u = os.environ.get("KAGGLE_USERNAME")
    if not u:
        sys.exit("Set KAGGLE_USERNAME (your Kaggle handle) and KAGGLE_API_TOKEN or KAGGLE_KEY.")
    if not (os.environ.get("KAGGLE_API_TOKEN") or os.environ.get("KAGGLE_KEY")
            or os.path.exists(os.path.expanduser("~/.kaggle/kaggle.json"))):
        sys.exit("Set KAGGLE_API_TOKEN (Kaggle > Settings > API > Create New Token) or KAGGLE_KEY.")
    return u


def kernel_id(dry=False):
    if dry and not os.environ.get("KAGGLE_USERNAME"):
        return f"YOUR-KAGGLE-USERNAME/{SLUG}"
    return f"{user()}/{SLUG}"


def load_state():
    if os.path.exists(STATE):
        with open(STATE) as f:
            return json.load(f)
    return None


def save_state(st):
    os.makedirs(BUILD, exist_ok=True)
    with open(STATE, "w") as f:
        json.dump(st, f, indent=2)


def status():
    """One of: none, queued, running, complete, error, cancelled, unknown (plus the raw text)."""
    out = kaggle("kernels", "status", kernel_id(), capture=True, check=False)
    low = out.lower()
    if "404" in low or "not found" in low:
        return "none", out.strip()
    for word, key in (("cancel", "cancelled"), ("error", "error"), ("complete", "complete"),
                      ("running", "running"), ("queued", "queued")):
        if word in low:
            return key, out.strip()
    return "unknown", out.strip()


def done_ids():
    if not os.path.isdir(RENDERS):
        return set()
    return {f[:-4] for f in os.listdir(RENDERS) if f.endswith(".mp4")}


def cmd_check(_):
    kid = kernel_id()
    print(kaggle("kernels", "list", "--mine", "--page-size", "5", capture=True).strip() or "(no kernels yet)")
    print(kaggle("quota", capture=True, check=False).strip())
    print(f"kernel id: {kid}; status: {status()[0]}")


def cmd_push(a):
    if not a.dry_run:
        st_now, raw = status()
        if st_now in ("queued", "running"):
            sys.exit(f"{kernel_id()} is {st_now}; wait for it (python submit.py wait) before pushing again.\n{raw}")
        last = load_state()
        if last and not last.get("fetched") and st_now in ("complete", "error", "cancelled"):
            print("fetching the previous run's outputs first (a new push replaces them on Kaggle)")
            cmd_fetch(a)
    kid = kernel_id(dry=a.dry_run)

    with open(a.shots) as f:
        spec = json.load(f)
    shots = spec["shots"]
    if a.only:
        want = set(a.only.split(","))
        unknown = want - {s["id"] for s in shots}
        if unknown:
            sys.exit(f"unknown shot ids: {sorted(unknown)}")
        shots = [s for s in shots if s["id"] in want]
    have = done_ids()
    todo = [s for s in shots if s["id"] not in have or a.redo]
    if not todo:
        sys.exit("every selected shot already has renders/<id>.mp4 (use --redo to render again)")

    shutil.rmtree(KERNEL_DIR, ignore_errors=True)
    os.makedirs(KERNEL_DIR)
    files = {}
    for name in ("render.py", "lowmem.py"):
        with open(os.path.join(HERE, name), "rb") as f:
            files[name] = base64.b64encode(f.read()).decode()
    files["shots.json"] = base64.b64encode(json.dumps({"shots": todo}, ensure_ascii=False).encode()).decode()
    args = ["--steps", str(a.steps), "--budget-hours", str(a.budget_hours)]
    with open(os.path.join(KERNEL_DIR, "t3_render.py"), "w") as f:
        f.write(BOOTSTRAP.format(files=json.dumps(files, indent=1), args=json.dumps(args)))
    meta = {
        "id": kid, "title": SLUG, "code_file": "t3_render.py", "language": "python",
        "kernel_type": "script", "is_private": True, "enable_gpu": True, "enable_internet": True,
        "machine_shape": ACCELERATOR, "dataset_sources": [], "competition_sources": [],
        "kernel_sources": [], "model_sources": [],
    }
    with open(os.path.join(KERNEL_DIR, "kernel-metadata.json"), "w") as f:
        json.dump(meta, f, indent=2)
    print(f"{len(todo)} shot(s) at {a.steps} steps for {kid} on {ACCELERATOR}: {', '.join(s['id'] for s in todo)}")
    if a.dry_run:
        print(f"dry run: kernel written to {KERNEL_DIR}, nothing pushed")
        return
    kaggle("kernels", "push", "-p", KERNEL_DIR, "--accelerator", ACCELERATOR)
    save_state({"kernel": kernel_id(), "pushed_at": time.strftime("%Y-%m-%d %H:%M:%S"),
                "shots": [s["id"] for s in todo], "steps": a.steps, "fetched": False})
    print(f"started. Watch: https://www.kaggle.com/code/{kid}  or  python submit.py logs --follow")


def cmd_status(_):
    st, raw = status()
    print(st)
    print(raw)
    last = load_state()
    if last:
        print(f"last push {last['pushed_at']}: {', '.join(last['shots'])} (fetched: {last['fetched']})")


def cmd_logs(a):
    args = ["kernels", "logs", kernel_id()] + (["--follow"] if a.follow else [])
    kaggle(*args, check=False)


def cmd_fetch(_):
    out = os.path.join(BUILD, "output")
    shutil.rmtree(out, ignore_errors=True)
    os.makedirs(out)
    kaggle("kernels", "output", kernel_id(), "-p", out, "--force")
    os.makedirs(os.path.join(RENDERS, "latents"), exist_ok=True)
    os.makedirs(os.path.join(RENDERS, "logs"), exist_ok=True)
    got = []
    for root, _, names in os.walk(out):
        for n in names:
            src = os.path.join(root, n)
            if (n.endswith(".mp4") and not n.endswith(".part.mp4")) or (n.endswith(".json") and "renders" in root):
                shutil.move(src, os.path.join(RENDERS, n))
                got.append(n)
            elif n.endswith(".pt"):
                shutil.move(src, os.path.join(RENDERS, "latents", n))
            elif n.endswith(".log") or n == "summary.json":
                shutil.move(src, os.path.join(RENDERS, "logs", time.strftime("%Y%m%d-%H%M%S-") + n))
    st = load_state() or {}
    st["fetched"] = True
    save_state(st)
    print(f"fetched {len([g for g in got if g.endswith('.mp4')])} video(s) into {RENDERS}: {sorted(got)}")
    summary = [f for f in os.listdir(os.path.join(RENDERS, "logs")) if f.endswith("summary.json")]
    if summary:
        with open(os.path.join(RENDERS, "logs", sorted(summary)[-1])) as f:
            print("run summary:", f.read().strip())


def cmd_wait(a):
    while True:
        st, raw = status()
        print(time.strftime("%H:%M:%S"), st, flush=True)
        if st in ("complete", "error", "cancelled"):
            if st != "complete":
                print(raw)
            cmd_fetch(a)
            return
        if st == "none":
            sys.exit("no run found; push first")
        time.sleep(a.every)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("check").set_defaults(fn=cmd_check)
    p = sub.add_parser("push")
    p.add_argument("--shots", default=os.path.join(HERE, "shots.json"))
    p.add_argument("--only", help="comma-separated shot ids")
    p.add_argument("--steps", type=int, default=15, help="denoising steps (paper 50, demo 15)")
    p.add_argument("--budget-hours", type=float, default=11.3)
    p.add_argument("--redo", action="store_true", help="render even if renders/<id>.mp4 exists")
    p.add_argument("--dry-run", action="store_true", help="build build/kernel/ but do not push")
    p.set_defaults(fn=cmd_push)
    sub.add_parser("status").set_defaults(fn=cmd_status)
    lg = sub.add_parser("logs")
    lg.add_argument("--follow", action="store_true")
    lg.set_defaults(fn=cmd_logs)
    sub.add_parser("fetch").set_defaults(fn=cmd_fetch)
    w = sub.add_parser("wait")
    w.add_argument("--every", type=int, default=900, help="seconds between status checks")
    w.set_defaults(fn=cmd_wait)
    a = ap.parse_args()
    a.fn(a)


if __name__ == "__main__":
    main()
